package sports.club.management.system;
import sports.club.management.system.domain.*;
import sports.club.management.system.service.SportFactory;
import sports.club.management.system.service.Storage;

public class Main {
    public static void main(String[] args) {
        Sport football = SportFactory.createTeamSport("Football");
        Sport boxing = SportFactory.createIndividualSport("Boxing");

        Athlete a1 = new Athlete.Builder().setName("Yersultan").setAge(17).setSport(football).build();
        Athlete a2 = new Athlete.Builder().setName("Daniel").setAge(18).setSport(boxing).build();
        Athlete a3 = new Athlete.Builder().setName("Miras").setAge(19).setSport(football).build();

        Storage<Athlete> athleteStorage = new Storage<>();
        athleteStorage.add(a1); athleteStorage.add(a2);
        athleteStorage.add(a3);

        Athlete[] athletes = {a1,a2,a3};


        SportsClub club = new SportsClub("AITU Sports Club",athletes);

        club.printAllAthletes();

        System.out.println("\nOldest athlete");
        club.findOldestAthlete().printInfo();

        System.out.println();
        club.printTeamSportAthletes();

        System.out.println("\nAthletes older than 18:");
        club.printFilteredAthletes(a -> a.getAge()>18);

    }

}
































































































































































































































